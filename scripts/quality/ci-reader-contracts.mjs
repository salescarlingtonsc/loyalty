/* NESTLY v723 — CI-100 check 92 (UI/RPC contract validation).
 *
 * WHY THIS EXISTS. Customer Intelligence has 25 public.get_ci_* readers plus
 * get_customer_intelligence_v83 and app.v176_evidence_pack, and a growing set of app.js panel
 * renderers that read specific keys off their payloads. Nothing before this file wrote down,
 * in one place, which top-level keys each reader is contractually required to emit, or which
 * nested keys a renderer actually reads — so a reader could rename or drop a key (the exact
 * defect class nestly_v667 found in platform-console.js's consultative brief: superseded key
 * names that were always undefined) and nothing would fail except a human eyeballing pixels.
 *
 * THIS FILE IS THE SINGLE SOURCE. It writes TWO artifacts from the one CONTRACTS object below:
 *   1. docs/design/ci/CI-READER-CONTRACTS.json — the machine-readable contract, read by the JS
 *      test suites (tests/business-ui/v723-ci-reader-contracts.test.mjs,
 *      tests/platform-console/v723-ci-reader-contracts.test.mjs).
 *   2. an embedded literal inside db/tests/executed/v723_corpus_reader_contracts.sql, between
 *      the CI-READER-CONTRACTS-EMBED markers — because the db-tests harness runs each executed
 *      fixture through plain `psql -f` against an ephemeral cluster with no filesystem access
 *      granted to the SQL session (no `\set` + `pg_read_file`, see
 *      docs/qa/CI-CORPUS-FIXTURE-GUIDE.md), so the fixture cannot read the JSON file at
 *      run time. Baking the identical JSON in as a SQL string literal is the only way the SQL
 *      side can assert against the SAME contract the UI side asserts against, rather than a
 *      hand-copied — and driftable — second version of it.
 *
 * A test (tests/business-ui/v723-ci-reader-contracts.test.mjs) asserts the embedded literal and
 * the JSON file parse to deeply-equal objects, so this generator is the only place either can be
 * edited; hand-editing one without the other fails CI.
 *
 * USAGE
 *   node scripts/quality/ci-reader-contracts.mjs           regenerate both artifacts
 *   node scripts/quality/ci-reader-contracts.mjs --check    exit non-zero if either is stale
 *
 * TYPE NOTATION. Each declared type is one (or, joined by "|", several) of the six values
 * `jsonb_typeof()` can return: object, array, string, number, boolean, null. A key whose value
 * is sometimes null under real (evidence-gated / not-yet-computed) conditions — e.g. an
 * evidence-floor figure that is null until enough samples exist — is declared "TYPE|null"; the
 * SQL assertion accepts either. `required` lists TOP-LEVEL keys every reader call must emit
 * regardless of how thin the tenant's data is (proven against a deliberately minimal fixture,
 * db/tests/executed/v723_corpus_reader_contracts.sql — six customers, six sales, no consent
 * grants, no packages, no discounts: BELOW every evidence floor in this codebase, so a key that
 * only appears once the fixture is "rich enough" would not pass this contract vacuously).
 * `nested` lists the dotted paths a page renderer actually reads off the payload — `.*` denotes
 * "for every element of the preceding array" — and is populated ONLY for the 9 get_ci_* readers
 * plus get_customer_intelligence_v83 that app/app.js's Customer Intelligence page consumes
 * directly; the other 16 readers carry `nested: {}` because no renderer reads into them yet.
 * `optional: true` marks a nested key the renderer only reads when its parent is non-null
 * (e.g. funnel.join, which nestly_v698's own daypart-style envelope omits entirely rather than
 * nulls when the funnel-counter table has zero rows for this scope).
 */
